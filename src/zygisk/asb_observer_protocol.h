#define ASB_OBSERVER_MAGIC 0x4153425au /* "ASBZ" */
#define ASB_OBSERVER_VERSION 2u
#define ASB_OBSERVER_EVENT_PROCESS_START 1u  /* allowlisted process; connection kept for exit */
#define ASB_OBSERVER_EVENT_SPAWN 2u          /* one-shot: cold-start and/or ledger record */
#define ASB_OBSERVER_FLAG_TOP_APP 1u         /* zygote started it as the top app */
#define ASB_OBSERVER_FLAG_LAUNCH 2u          /* ask the governor to cover the launch */
#define ASB_OBSERVER_FLAG_LEDGER 4u          /* count it in the process-start ledger */
#define ASB_OBSERVER_FLAGS_KNOWN 7u
#define ASB_OBSERVER_MAX_PROCESSES 64u
#define ASB_OBSERVER_MAX_EVENTS_PER_MINUTE 64u
#define ASB_OBSERVER_HINT_MAX_PER_MINUTE 8u
#define ASB_OBSERVER_HINT_MIN_INTERVAL_MS 2000
#define ASB_OBSERVER_LAUNCH_MAX_PER_MINUTE 20u
#define ASB_OBSERVER_LAUNCH_MIN_INTERVAL_MS 1000
#define ASB_OBSERVER_LEDGER_MAX 128u
#define ASB_OBSERVER_BURST_WINDOW_MS 300000
#define ASB_OBSERVER_BURST_KEEP 32u
#define ASB_OBSERVER_RSS_TTL_MS 30000
#define ASB_OBSERVER_POLICY_MAX_BYTES 12288u

#pragma pack(push, 1)
struct AsbObserverFrame {
    uint32_t magic;
    uint16_t version;
    uint16_t kind;
    uint32_t size;
    int32_t pid;
    uint32_t flags;
    uint64_t process_start_ticks;
    int64_t monotonic_ms;
    char package[128];
};
#pragma pack(pop)

inline int64_t asb_observer_monotonic_ms() {
    struct timespec ts {};
    return clock_gettime(CLOCK_MONOTONIC, &ts) == 0
        ? static_cast<int64_t>(ts.tv_sec) * 1000 + ts.tv_nsec / 1000000 : 0;
}

inline std::string asb_observer_base_package(const std::string &process_name) {
    const size_t colon = process_name.find(':');
    return process_name.substr(0, colon);
}

inline bool asb_observer_package_valid(const std::string &package) {
    if (package.size() < 3 || package.size() > 127 || package.find('.') == std::string::npos)
        return false;
    if (package.front() == '.' || package.back() == '.' || package.find("..") != std::string::npos)
        return false;
    for (unsigned char c : package) {
        if (!(std::isalnum(c) || c == '_' || c == '.')) return false;
    }
    return true;
}

inline bool asb_observer_package_denied(const std::string &process_name) {
    static const char *const exact[] = {
        "system_server", "com.android.systemui", "com.android.packageinstaller",
        "com.android.permissioncontroller", "com.android.settings", "com.android.phone",
        "com.android.providers.media", "com.android.providers.downloads",
        "me.weishu.kernelsu", "com.rifsxd.ksunext", "com.topjohnwu.magisk",
        "io.github.vvb2060.magisk", "org.lsposed.manager", "com.tsng.hidemyapplist"
    };
    static const char *const prefixes[] = {
        "android.", "com.android.shell", "com.qualcomm.", "com.qti.", "vendor.",
        "com.oplus.safecenter", "com.coloros.safecenter", "com.heytap.safecenter"
    };
    if (process_name == "system_server" || process_name == "zygote" ||
        process_name == "zygote64" || process_name == "zygote32") return true;
    const std::string base = asb_observer_base_package(process_name);
    for (const char *value : exact) if (base == value) return true;
    for (const char *value : prefixes) {
        const size_t n = std::strlen(value);
        if (base.compare(0, n, value) == 0) return true;
    }
    return false;
}

/* Ordinary installed applications only: app ids 10000-19999 of any user. Isolated services,
 * app-zygote children, SDK sandboxes and system uids never reach a syscall in the hot path. */
inline bool asb_observer_regular_app_uid(int uid) {
    if (uid < 0) return false;
    const int app_id = uid % 100000;
    return app_id >= 10000 && app_id <= 19999;
}

inline bool asb_observer_frame_valid(const AsbObserverFrame &frame) {
    if (frame.magic != ASB_OBSERVER_MAGIC || frame.version != ASB_OBSERVER_VERSION ||
        frame.size != sizeof(AsbObserverFrame) || frame.pid <= 1 || frame.monotonic_ms <= 0 ||
        (frame.flags & ~ASB_OBSERVER_FLAGS_KNOWN) != 0) return false;
    if (std::memchr(frame.package, '\0', sizeof(frame.package)) == nullptr) return false;
    const std::string package(frame.package);
    if (frame.kind == ASB_OBSERVER_EVENT_PROCESS_START)
        return asb_observer_package_valid(package) && !asb_observer_package_denied(package);
    if (frame.kind != ASB_OBSERVER_EVENT_SPAWN) return false;
    if (!(frame.flags & (ASB_OBSERVER_FLAG_LAUNCH | ASB_OBSERVER_FLAG_LEDGER))) return false;
    if ((frame.flags & ASB_OBSERVER_FLAG_LAUNCH) && !(frame.flags & ASB_OBSERVER_FLAG_TOP_APP))
        return false;
    /* A launch-only event names no package; a ledger event must name a valid one. */
    if (frame.flags & ASB_OBSERVER_FLAG_LEDGER)
        return asb_observer_package_valid(package) && !asb_observer_package_denied(package);
    return package.empty();
}

/* The generated policy: "key=value" lines, at most 64 "pkg=" lines. Anything malformed
 * makes the whole policy invalid, and an invalid policy observes nothing. */
struct AsbObserverPolicy {
    bool valid = false;
    bool observer = false, hints = false, launch = false, ledger = false;
    unsigned long generation = 0;
    unsigned packages = 0;
    char package[ASB_OBSERVER_MAX_PROCESSES][128] {};

    bool active() const { return valid && ((observer && packages) || launch || ledger); }
    bool selected(const char *base) const {
        if (!valid || !observer || !base || !*base) return false;
        for (unsigned i = 0; i < packages; ++i) if (std::strcmp(package[i], base) == 0) return true;
        return false;
    }
};

inline bool asb_observer_policy_flag(const char *v, size_t n, bool &out) {
    if (n != 1 || (v[0] != '0' && v[0] != '1')) return false;
    out = v[0] == '1';
    return true;
}

inline bool asb_observer_policy_parse(const char *text, size_t len, AsbObserverPolicy &out) {
    out = AsbObserverPolicy();
    if (!text || !len || len > ASB_OBSERVER_POLICY_MAX_BYTES) return false;
    bool version = false;
    size_t pos = 0;
    while (pos < len) {
        const char *line = text + pos;
        const char *nl = static_cast<const char *>(std::memchr(line, '\n', len - pos));
        const size_t n = nl ? static_cast<size_t>(nl - line) : len - pos;
        pos += n + (nl ? 1 : 0);
        if (!n) continue;
        const char *eq = static_cast<const char *>(std::memchr(line, '=', n));
        if (!eq) return false;
        const size_t kn = static_cast<size_t>(eq - line);
        const char *v = eq + 1;
        const size_t vn = n - kn - 1;
        if (kn == 1 && line[0] == 'v') {
            if (vn != 1 || v[0] != '2') return false;
            version = true;
        } else if (kn == 3 && std::memcmp(line, "gen", 3) == 0) {
            if (!vn || vn > 12) return false;
            unsigned long g = 0;
            for (size_t i = 0; i < vn; ++i) {
                if (v[i] < '0' || v[i] > '9') return false;
                g = g * 10 + static_cast<unsigned long>(v[i] - '0');
            }
            out.generation = g;
        } else if (kn == 8 && std::memcmp(line, "observer", 8) == 0) {
            if (!asb_observer_policy_flag(v, vn, out.observer)) return false;
        } else if (kn == 5 && std::memcmp(line, "hints", 5) == 0) {
            if (!asb_observer_policy_flag(v, vn, out.hints)) return false;
        } else if (kn == 6 && std::memcmp(line, "launch", 6) == 0) {
            if (!asb_observer_policy_flag(v, vn, out.launch)) return false;
        } else if (kn == 6 && std::memcmp(line, "ledger", 6) == 0) {
            if (!asb_observer_policy_flag(v, vn, out.ledger)) return false;
        } else if (kn == 3 && std::memcmp(line, "pkg", 3) == 0) {
            if (out.packages >= ASB_OBSERVER_MAX_PROCESSES || vn >= sizeof(out.package[0])) return false;
            const std::string p(v, vn);
            if (!asb_observer_package_valid(p) || asb_observer_package_denied(p)) return false;
            std::memcpy(out.package[out.packages], v, vn);
            out.package[out.packages][vn] = 0;
            ++out.packages;
        } else {
            return false;
        }
    }
    out.valid = version;
    return out.valid;
}

